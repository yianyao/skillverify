def generate_questions(num: int = 20, seed: int | None = None) -> list[str]:
    """从题库中不放回随机抽取 num 条问题。"""
    if seed is not None:
        random.seed(seed)

    pool = [(cat, q) for cat, qs in QUESTION_POOL.items() for q in qs]
    if num > len(pool):
        raise ValueError(f"题库只有 {len(pool)} 条问题，无法抽取 {num} 条")

    sampled = random.sample(pool, num)
    return [f"[{cat}] {q}" for cat, q in sampled]


